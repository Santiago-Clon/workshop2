PROJECT_ROOT = Path(__file__).resolve().parent.parent
LOG_DIR = PROJECT_ROOT / "logs"
LOG_DIR.mkdir(parents=True, exist_ok=True)

REPORT_PATH = LOG_DIR / "load_dw_latest.json"

DB_CONFIG = {
    "host": os.getenv("ETL_DB_HOST", "localhost"),
    "port": int(os.getenv("ETL_DB_PORT", "5433")),
    "database": os.getenv("ETL_DB_NAME", "etl_workshop"),
    "username": os.getenv("ETL_DB_USER", "etl_user"),
    "password": os.getenv("ETL_DB_PASSWORD", "etl_password"),
}

PREPARED_SCHEMA = "prepared"
DW_SCHEMA = "dw"


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def write_report(report: dict) -> None:
    REPORT_PATH.write_text(
        json.dumps(report, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )


def create_engine_from_config():
    url = URL.create(
        drivername="postgresql+psycopg2",
        username=DB_CONFIG["username"],
        password=DB_CONFIG["password"],
        host=DB_CONFIG["host"],
        port=DB_CONFIG["port"],
        database=DB_CONFIG["database"],
    )
    return create_engine(url, pool_pre_ping=True)


# ---------------------------------------------------------
# 1. Mandatory PREPARED validation gate
# ---------------------------------------------------------

def run_prepared_validation(report: dict) -> None:
    validation_script = PROJECT_ROOT / "src" / "prepared_validation.py"

    if not validation_script.exists():
        raise FileNotFoundError(
            f"Validation script not found: {validation_script}"
        )

    result = subprocess.run(
        [sys.executable, str(validation_script)],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )

    report["prepared_validation"] = {
        "script": str(validation_script),
        "return_code": result.returncode,
        "stdout": result.stdout[-4000:],
        "stderr": result.stderr[-4000:],
    }

    if result.returncode != 0:
        raise RuntimeError(
            "PREPARED validation failed. DW loading has been blocked."
        )


