# ---------------------------------------------------------
# 3. PREPARED preflight checks
# ---------------------------------------------------------

REQUIRED_TABLES = {
    "spotify_tracks",
    "spotify_track_artists",
    "grammy_nominations",
    "grammy_artist_candidates",
    "track_grammy_matches",
}


def check_prepared_tables(conn, report: dict) -> None:
    result = conn.execute(
        text("""
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = :schema
              AND table_type = 'BASE TABLE'
        """),
        {"schema": PREPARED_SCHEMA},
    )

    existing = {row[0] for row in result.fetchall()}
    missing = sorted(REQUIRED_TABLES - existing)

    report["prepared_preflight"] = {
        "required_tables": sorted(REQUIRED_TABLES),
        "existing_tables": sorted(existing),
        "missing_tables": missing,
    }

    if missing:
        raise RuntimeError(
            f"Missing PREPARED tables: {', '.join(missing)}"
        )

    counts = {}
    for table in sorted(REQUIRED_TABLES):
        count = conn.execute(
            text(f'SELECT COUNT(*) FROM prepared."{table}"')
        ).scalar_one()
        counts[table] = count

    report["prepared_preflight"]["row_counts"] = counts

    for table in (
        "spotify_tracks",
        "spotify_track_artists",
        "grammy_nominations",
        "grammy_artist_candidates",
    ):
        if counts[table] == 0:
            raise RuntimeError(
                f"Required PREPARED table is empty: {table}"
            )

    # Each fact row must be uniquely identified by track_id + track_genre.
    duplicate_tracks = conn.execute(
        text("""
            SELECT COUNT(*)
            FROM (
                SELECT track_id, track_genre
                FROM prepared.spotify_tracks
                GROUP BY track_id, track_genre
                HAVING COUNT(*) > 1
            ) AS duplicated
        """)
    ).scalar_one()

    if duplicate_tracks:
        raise RuntimeError(
            f"PREPARED has {duplicate_tracks} duplicated track/genre keys."
        )

    # Artist associations must point to existing Spotify track/genre rows.
    orphan_artist_associations = conn.execute(
        text("""
            SELECT COUNT(*)
            FROM prepared.spotify_track_artists AS a
            LEFT JOIN prepared.spotify_tracks AS s
              ON s.track_id = a.track_id
             AND s.track_genre = a.track_genre
            WHERE s.track_id IS NULL
        """)
    ).scalar_one()

    if orphan_artist_associations:
        raise RuntimeError(
            "Spotify artist associations reference missing track/genre rows."
        )

    # Grammy matches must point to existing Spotify track/genre rows.
    orphan_grammy_matches = conn.execute(
        text("""
            SELECT COUNT(*)
            FROM prepared.track_grammy_matches AS m
            LEFT JOIN prepared.spotify_tracks AS s
              ON s.track_id = m.track_id
             AND s.track_genre = m.track_genre
            WHERE s.track_id IS NULL
        """)
    ).scalar_one()

    if orphan_grammy_matches:
        raise RuntimeError(
            "Grammy matches reference missing track/genre rows."
        )

    report["prepared_preflight"]["duplicate_track_genre_keys"] = (
        duplicate_tracks
    )
    report["prepared_preflight"]["orphan_artist_associations"] = (
        orphan_artist_associations
    )
    report["prepared_preflight"]["orphan_grammy_matches"] = (
        orphan_grammy_matches
    )


# ---------------------------------------------------------
# 4. Load dimensions
# ---------------------------------------------------------

def load_dimensions(conn) -> None:
    # Prefer the Spotify display name for artists already present there.
    conn.execute(text("""
        INSERT INTO dw.dim_artist (
            artist_name,
            artist_name_normalized
        )
        SELECT DISTINCT ON (artist_name_normalized)
            LEFT(TRIM(artist_name), 255),
            artist_name_normalized
        FROM prepared.spotify_track_artists
        WHERE NULLIF(TRIM(artist_name), '') IS NOT NULL
          AND NULLIF(TRIM(artist_name_normalized), '') IS NOT NULL
        ORDER BY artist_name_normalized, artist_name
        ON CONFLICT (artist_name_normalized)
        DO UPDATE SET artist_name = EXCLUDED.artist_name
    """))

    # Add Grammy artists not already represented in the dimension.
    conn.execute(text("""
        INSERT INTO dw.dim_artist (
            artist_name,
            artist_name_normalized
        )
        SELECT DISTINCT ON (artist_name_normalized)
            LEFT(TRIM(artist_name), 255),
            artist_name_normalized
        FROM prepared.grammy_artist_candidates
        WHERE NULLIF(TRIM(artist_name), '') IS NOT NULL
          AND NULLIF(TRIM(artist_name_normalized), '') IS NOT NULL
        ORDER BY artist_name_normalized, artist_name
        ON CONFLICT (artist_name_normalized) DO NOTHING
    """))

    conn.execute(text("""
        INSERT INTO dw.dim_genre (genre_name)
        SELECT DISTINCT TRIM(track_genre)
        FROM prepared.spotify_tracks
        WHERE NULLIF(TRIM(track_genre), '') IS NOT NULL
        ON CONFLICT (genre_name) DO NOTHING
    """))

    # One dimensional record per year + normalized category.
    # category_normalized prevents case/whitespace variants from creating
    # separate members for the same business category.
    conn.execute(text("""
        INSERT INTO dw.dim_grammy_record (
            year,
            category,
            category_normalized
        )
        SELECT DISTINCT ON (year, category_norm)
            year::SMALLINT,
            LEFT(TRIM(category), 255),
            LEFT(TRIM(category_norm), 255)
        FROM prepared.grammy_nominations
        WHERE year IS NOT NULL
          AND NULLIF(TRIM(category), '') IS NOT NULL
          AND NULLIF(TRIM(category_norm), '') IS NOT NULL
        ORDER BY year, category_norm, category
        ON CONFLICT (year, category_normalized)
        DO UPDATE SET category = EXCLUDED.category
    """))


# ---------------------------------------------------------
# 5. Load fact table and bridge tables
# ---------------------------------------------------------

def load_fact_track(conn) -> None:
    conn.execute(text("""
        INSERT INTO dw.fact_track (
            track_id,
            genre_key,
            popularity,
            duration_ms,
            danceability,
            energy,
            loudness,
            speechiness,
            acousticness,
            instrumentalness,
            liveness,
            valence,
            tempo
        )
        SELECT
            s.track_id,
            g.genre_key,
            s.popularity::SMALLINT,
            s.duration_ms::INTEGER,
            s.danceability::NUMERIC(6,4),
            s.energy::NUMERIC(6,4),
            s.loudness::NUMERIC(8,3),
            s.speechiness::NUMERIC(6,4),
            s.acousticness::NUMERIC(6,4),
            s.instrumentalness::NUMERIC(6,4),
            s.liveness::NUMERIC(6,4),
            s.valence::NUMERIC(6,4),
            s.tempo::NUMERIC(8,3)
        FROM prepared.spotify_tracks AS s
        JOIN dw.dim_genre AS g
          ON g.genre_name = TRIM(s.track_genre)
        WHERE NULLIF(TRIM(s.track_id), '') IS NOT NULL
          AND NULLIF(TRIM(s.track_genre), '') IS NOT NULL
    """))


def load_bridge_track_artist(conn) -> None:
    conn.execute(text("""
        INSERT INTO dw.bridge_track_artist (track_key, artist_key)
        SELECT DISTINCT
            f.track_key,
            a.artist_key
        FROM prepared.spotify_track_artists AS s
        JOIN dw.fact_track AS f
          ON f.track_id = s.track_id
        JOIN dw.dim_genre AS g
          ON g.genre_key = f.genre_key
         AND g.genre_name = TRIM(s.track_genre)
        JOIN dw.dim_artist AS a
          ON a.artist_name_normalized = s.artist_name_normalized
        WHERE NULLIF(TRIM(s.artist_name_normalized), '') IS NOT NULL
        ON CONFLICT (track_key, artist_key) DO NOTHING
    """))


def load_bridge_track_grammy(conn) -> None:
    conn.execute(text("""
        INSERT INTO dw.bridge_track_grammy (
            track_key,
            grammy_record_key,
            match_method,
            match_role
        )
        SELECT DISTINCT
            f.track_key,
            d.grammy_record_key,
            LEFT(m.match_method, 30),
            LEFT(m.match_role, 50)
        FROM prepared.track_grammy_matches AS m
        JOIN dw.fact_track AS f
          ON f.track_id = m.track_id
        JOIN dw.dim_genre AS g
          ON g.genre_key = f.genre_key
         AND g.genre_name = TRIM(m.track_genre)
        JOIN dw.dim_grammy_record AS d
          ON d.year = m.grammy_year::SMALLINT
         AND d.category_normalized =
             LEFT(TRIM(m.grammy_category_normalized), 255)
        ON CONFLICT (track_key, grammy_record_key)
        DO UPDATE SET
            match_method = EXCLUDED.match_method,
            match_role = EXCLUDED.match_role
    """))


# ---------------------------------------------------------
# 6. Post-load checks
# ---------------------------------------------------------

def collect_dw_metrics(conn) -> dict:
    tables = [
        "dim_artist",
        "dim_genre",
        "dim_grammy_record",
        "fact_track",
        "bridge_track_artist",
        "bridge_track_grammy",
    ]

    counts = {}
    for table in tables:
        counts[table] = conn.execute(
            text(f"SELECT COUNT(*) FROM dw.{table}")
        ).scalar_one()

    duplicate_fact_keys = conn.execute(text("""
        SELECT COUNT(*)
        FROM (
            SELECT track_id, genre_key
            FROM dw.fact_track
            GROUP BY track_id, genre_key
            HAVING COUNT(*) > 1
        ) AS d
    """)).scalar_one()

    orphan_artist_bridge_rows = conn.execute(text("""
        SELECT COUNT(*)
        FROM dw.bridge_track_artist AS b
        LEFT JOIN dw.fact_track AS f ON f.track_key = b.track_key
        LEFT JOIN dw.dim_artist AS a ON a.artist_key = b.artist_key
        WHERE f.track_key IS NULL OR a.artist_key IS NULL
    """)).scalar_one()

    orphan_grammy_bridge_rows = conn.execute(text("""
        SELECT COUNT(*)
        FROM dw.bridge_track_grammy AS b
        LEFT JOIN dw.fact_track AS f ON f.track_key = b.track_key
        LEFT JOIN dw.dim_grammy_record AS d
          ON d.grammy_record_key = b.grammy_record_key
        WHERE f.track_key IS NULL OR d.grammy_record_key IS NULL
    """)).scalar_one()

    return {
        "row_counts": counts,
        "duplicate_fact_track_genre_keys": duplicate_fact_keys,
        "orphan_track_artist_bridge_rows": orphan_artist_bridge_rows,
        "orphan_track_grammy_bridge_rows": orphan_grammy_bridge_rows,
    }


def validate_dw_metrics(metrics: dict) -> None:
    if metrics["row_counts"]["fact_track"] == 0:
        raise RuntimeError("DW fact_track is empty.")

    if metrics["duplicate_fact_track_genre_keys"] != 0:
        raise RuntimeError("DW fact_track contains duplicate track/genre keys.")

    if metrics["orphan_track_artist_bridge_rows"] != 0:
        raise RuntimeError("DW bridge_track_artist contains orphan rows.")

    if metrics["orphan_track_grammy_bridge_rows"] != 0:
        raise RuntimeError("DW bridge_track_grammy contains orphan rows.")


# ---------------------------------------------------------
# 7. Main pipeline
# ---------------------------------------------------------

def main() -> int:
    report = {
        "process": "DW_LOAD",
        "started_at": utc_now(),
        "execution_status": "RUNNING",
        "rules": {},
        "exceptions": [],
    }

    engine = None

    try:
        # Gate: do not load anything if PREPARED validation fails.
        run_prepared_validation(report)
        report["rules"]["LD-01"] = "PASS"

        engine = create_engine_from_config()

        # Transactional load: a failure rolls back the DW changes.
        with engine.begin() as conn:
            conn.execute(text("SELECT 1"))
            check_prepared_tables(conn, report)
            report["rules"]["LD-02"] = "PASS"

            create_dw_schema(conn)
            report["rules"]["LD-03"] = "PASS"

            # Refresh facts and bridges from the current PREPARED snapshot.
            # Dimensions are upserted, retaining existing surrogate keys.
            conn.execute(text("DELETE FROM dw.bridge_track_grammy"))
            conn.execute(text("DELETE FROM dw.bridge_track_artist"))
            conn.execute(text("DELETE FROM dw.fact_track"))

            load_dimensions(conn)
            report["rules"]["LD-04"] = "PASS"

            load_fact_track(conn)
            load_bridge_track_artist(conn)
            load_bridge_track_grammy(conn)
            report["rules"]["LD-05"] = "PASS"

            metrics = collect_dw_metrics(conn)
            validate_dw_metrics(metrics)

            report["dw_metrics"] = metrics
            report["rules"]["LD-06"] = "PASS"

        report["execution_status"] = "SUCCESS"
        report["global_success"] = True

    except Exception as exc:
        report["execution_status"] = "FAILED"
        report["global_success"] = False
        report["exceptions"].append({
            "type": type(exc).__name__,
            "message": str(exc),
            "traceback": traceback.format_exc(),
        })

    finally:
        report["finished_at"] = utc_now()
        write_report(report)

        if engine is not None:
            engine.dispose()

    print(json.dumps(report, indent=2, ensure_ascii=False, default=str))

    return 0 if report["global_success"] else 1


if __name__ == "__main__":
    raise SystemExit(main())